# 4. Project Summary & Editable Phase Schedule
# ---------------------------------------------------------
def reconcile_phase_edits(old_df: pd.DataFrame, edited_df: pd.DataFrame) -> bool:
    """Fill missing Order values and keep Start/Duration/End consistent. Mutates edited_df.

    Returns True when anything changed and the page should rerun.
    """
    changed = False

    if edited_df["Order"].isnull().any():
        max_order = edited_df["Order"].max()
        max_order = 0 if pd.isna(max_order) else max_order
        for idx in edited_df[edited_df["Order"].isnull()].index:
            max_order += 1
            edited_df.at[idx, "Order"] = max_order
        changed = True

    for idx in edited_df.index:
        start_d = edited_df.loc[idx, "Start Date"]
        dur = edited_df.loc[idx, "Duration (Weeks)"]
        end_d = edited_df.loc[idx, "End Date"]
        if not (pd.notnull(start_d) and pd.notnull(dur)):
            continue

        calc_end = calculate_business_end_date(pd.to_datetime(start_d).date(), float(dur))
        if idx not in old_df.index or pd.isnull(end_d):
            if end_d != calc_end:
                edited_df.at[idx, "End Date"] = calc_end
                changed = True
            continue

        old_row = old_df.loc[idx]
        if old_row["Start Date"] != start_d or old_row["Duration (Weeks)"] != dur:
            # start or duration edited -> recompute end
            if end_d != calc_end:
                edited_df.at[idx, "End Date"] = calc_end
                changed = True
        elif old_row["End Date"] != end_d:
            # end edited -> recompute duration
            calc_dur = calculate_duration_weeks(pd.to_datetime(start_d).date(), pd.to_datetime(end_d).date())
            if dur != calc_dur:
                edited_df.at[idx, "Duration (Weeks)"] = calc_dur
                changed = True

    if not edited_df["Order"].equals(old_df["Order"]):
        changed = True
    return changed


if "tasks_df" in st.session_state:
    project_data = st.session_state["project_data"]

    st.subheader("Project Summary")
    st.write(project_data.project_summary)

    st.divider()
    st.subheader("Critical Insights and Risks")
    for risk in project_data.key_risks:
        st.warning(risk)

    st.divider()
    st.subheader("Phase Schedule")
    st.caption("High Level - Change the 'Order' number to rearrange tasks. This controls the Gantt chart.")

    if "Order" not in st.session_state["tasks_df"].columns:
        st.session_state["tasks_df"].insert(0, "Order", range(1, len(st.session_state["tasks_df"]) + 1))

    old_df = st.session_state["tasks_df"].copy().sort_values(by="Order").reset_index(drop=True)

    edited_df = st.data_editor(
        old_df,
        num_rows="dynamic",
        use_container_width=True,
        column_config={
            "Order": st.column_config.NumberColumn("Order", min_value=1, step=1, width="small"),
            "Phase": st.column_config.TextColumn("Phase"),
            "Duration (Weeks)": st.column_config.NumberColumn("Duration (Weeks)", min_value=0.1, max_value=50.0, step=0.5),
            "Start Date": st.column_config.DateColumn("Start Date", format="YYYY-MM-DD"),
            "End Date": st.column_config.DateColumn("End Date", format="YYYY-MM-DD"),
        },
    )

    if reconcile_phase_edits(old_df, edited_df):
        st.session_state["tasks_df"] = edited_df.sort_values(by="Order").reset_index(drop=True)
        st.rerun()

    # ---------------------------------------------------------
    # 5. Timeline Checks & Gantt Chart
    # ---------------------------------------------------------
    agreed_weeks = project_data.agreed_timeline_weeks
    deadline = deadline_date(safe_start, agreed_weeks)

    st.divider()
    max_end = latest_end_date(edited_df)
    if max_end is not None:
        if max_end > deadline:
            st.error(f"🚨 **Deadline Breach:** Tasks extend to {max_end.strftime('%B %d, %Y')}.")
        else:
            st.success(f"✅ **Timeline on Track:** Deliverables complete within the {agreed_weeks}-week boundary.")

    st.subheader("Gantt Chart")
    st.caption("Phase Schedule Visualization")

    chart_df = prepare_chart_df(edited_df)
    has_chart = not chart_df.empty
    if has_chart:
        min_date, num_weeks = week_axis(chart_df, safe_start, deadline)
        fig = build_gantt_figure(chart_df, min_date, num_weeks, deadline)
        st.plotly_chart(fig, use_container_width=True, config=GANTT_CHART_CONFIG)

    # ---------------------------------------------------------
    # 6. Proposed Sprint Distribution (Explicit Add/Delete)
    # ---------------------------------------------------------
    st.divider()

    col_header, col_btn = st.columns([8, 2])
    with col_header:
        st.subheader("Proposed Sprint Distribution")
    with col_btn:
        if st.button("➕ Add Sprint", use_container_width=True) and "visible_sprints" in st.session_state:
            visible = st.session_state["visible_sprints"]
            new_sprint = next_sprint_label(visible)
            if "Backlog" in visible:
                visible.insert(visible.index("Backlog"), new_sprint)
            else:
                visible.append(new_sprint)
            st.rerun()

    if "sprint_df" in st.session_state:
        master_sprint_df = st.session_state["sprint_df"]

        if "visible_sprints" not in st.session_state:
            existing = master_sprint_df["Sprint"].dropna().unique().tolist()
            highest = max((parse_sprint_number(s, 0) for s in existing), default=0)
            st.session_state["visible_sprints"] = initial_visible_sprints(highest)

        updated_dfs = []
        for sprint in st.session_state["visible_sprints"]:
            with st.expander(f"🟣 {sprint.upper()}", expanded=True):
                _, c2 = st.columns([9, 1])
                with c2:
                    if st.button("🗑️ Delete", key=f"del_{sprint}", help=f"Delete {sprint} and all its tasks"):
                        st.session_state["visible_sprints"].remove(sprint)
                        st.session_state["sprint_df"] = master_sprint_df[master_sprint_df["Sprint"] != sprint]
                        st.rerun()

                sprint_data = (
                    master_sprint_df[master_sprint_df["Sprint"] == sprint]
                    .drop(columns=["Sprint"], errors="ignore")
                    .reset_index(drop=True)
                )
                sprint_data.index = sprint_data.index + 1

                edited_sprint = st.data_editor(
                    sprint_data,
                    key=f"editor_{sprint}",
                    use_container_width=True,
                    num_rows="dynamic",
                    column_config={
                        "Name": st.column_config.TextColumn("Name", required=True, width="large"),
                        "Status": st.column_config.SelectboxColumn("Status", options=["To-Do", "In Progress", "In QA", "Blocked", "Complete", "Closed"], width="small"),
                        "Start date": st.column_config.DateColumn("Start date", format="YYYY-MM-DD", width="small"),
                        "Due date": st.column_config.DateColumn("Due date", format="YYYY-MM-DD", width="small"),
                        "Priority": st.column_config.SelectboxColumn("Priority", options=["Urgent", "High", "Normal", "Low"], width="small"),
                    },
                )
                edited_sprint.insert(0, "Sprint", sprint)
                updated_dfs.append(edited_sprint)

        if updated_dfs:
            st.session_state["sprint_df"] = pd.concat(updated_dfs, ignore_index=True)

    # ---------------------------------------------------------
    # 7. Export Center (CSV, Excel, PowerPoint)
    # ---------------------------------------------------------
    st.divider()
    st.subheader("Export Center")
    col1, col2, col3, col4, col5 = st.columns(5)

    with col1:
        st.download_button("Download Phase Schedule (CSV)", data=phase_schedule_csv(edited_df),
                           file_name="phase_schedule.csv", mime="text/csv")
    with col2:
        if "sprint_df" in st.session_state:
            st.download_button("Download Sprint Board (CSV)", data=sprint_board_csv(st.session_state["sprint_df"]),
                               file_name="sprint_distribution.csv", mime="text/csv")
    if has_chart:
        with col3:
            st.download_button("Download Excel Gantt", data=excel_gantt(chart_df, min_date, num_weeks),
                               file_name="gantt_grid.xlsx",
                               mime="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet")
        with col4:
            st.download_button("Download Editable PPTX", data=pptx_gantt(chart_df, min_date, num_weeks),
                               file_name="editable_gantt.pptx",
                               mime="application/vnd.openxmlformats-officedocument.presentationml.presentation",
                               type="primary")
    with col5:
        st.download_button("Download plan.json", data=project_data.model_dump_json(indent=2),
                           file_name="plan.json", mime="application/json",
                           help="Save the generated plan so you can reopen it later without regenerating.")
