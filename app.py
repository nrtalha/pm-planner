# ---------------------------------------------------------
# 3. Generate (Claude Code) or reopen a saved plan
# ---------------------------------------------------------
def apply_plan(project_data):
    st.session_state["project_data"] = project_data

    phase_df = pd.DataFrame([
        {"Task Name": t.task_name, "Phase": t.phase, "Duration (Weeks)": t.duration_weeks}
        for t in project_data.phase_tasks
    ])
    st.session_state["tasks_df"] = bootstrap_initial_schedule(phase_df, safe_start)

    sprint_df, max_sprint = build_sprint_rows(project_data.sprint_subtasks, safe_start)
    st.session_state["sprint_df"] = sprint_df
    st.session_state["visible_sprints"] = initial_visible_sprints(max_sprint)


if generate_btn:
    if uploaded_file is None:
        st.sidebar.warning("Upload a SOW PDF first.")
    else:
        with st.spinner("Claude is reading the SOW and building the plan. This usually takes 1–3 minutes..."):
            try:
                apply_plan(generate_plan(uploaded_file.getvalue(), target_timeline))
            except ClaudeCodeError as err:
                st.error(str(err))

if load_btn:
    if saved_plan is None:
        st.sidebar.warning("Choose a plan.json file first.")
    else:
        try:
            apply_plan(load_plan(saved_plan.getvalue().decode("utf-8")))
        except ValidationError as err:
            st.error(f"That plan.json does not match the expected format:\n\n{err}")


